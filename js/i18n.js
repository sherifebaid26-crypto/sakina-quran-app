let current = "en";

export function t(key, vars = {}) {
  const dict = current === "ar" ? AR : EN;
  let s = dict[key] ?? EN[key] ?? key;
  for (const [k, v] of Object.entries(vars)) {
    s = s.replaceAll("{" + k + "}", String(v));
  }
  return s;
}

export function getLang() { return current; }

export function setLang(lang) {
  current = lang === "ar" ? "ar" : "en";
  try { document.documentElement.lang = current; } catch {}
  try { document.documentElement.dir = current === "ar" ? "rtl" : "ltr"; } catch {}
}

export function fmtDate(date, opts = {}) {
  try {
    return new Date(date).toLocaleDateString(current === "ar" ? "ar-EG" : "en-US", opts);
  } catch { return String(date); }
}

export function fmtWeekday(date) {
  try {
    return new Date(date).toLocaleDateString(current === "ar" ? "ar-EG" : "en-US", { weekday: "long", month: "long", day: "numeric" });
  } catch { return ""; }
}
